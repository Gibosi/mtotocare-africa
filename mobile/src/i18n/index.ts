export let i18nReady: Promise<void> = Promise.resolve();

export const initI18n = async () => {
  let lng = 'en';
  try {
    const locales = Localization.getLocales();
    if (locales && locales.length > 0) {
      const code = locales[0].languageCode;
      if (code === 'sw' || code === 'swa') lng = 'sw';
    }
  } catch {
    // fallback to en
  }

  i18nReady = i18n
    .use(initReactI18next)
    .init({
      resources,
      lng,
      fallbackLng: 'en',
      interpolation: { escapeValue: false },
      compatibilityJSON: 'v3',
    })
    .then(() => undefined);
  return i18nReady;
};

// Do NOT auto-init. LanguageProvider controls initialization.
export default i18n;
